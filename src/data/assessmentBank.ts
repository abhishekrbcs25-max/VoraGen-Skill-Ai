export function getAssessmentQuestionsForSkill(skillName: string, role?: CareerRole): AssessmentQuestion[] {
  const targetNorm = skillName.trim().toLowerCase();
  for (const [bankSkill, bank] of Object.entries(ASSESSMENT_QUESTION_BANKS)) {
    const bankNorm = bankSkill.toLowerCase();
    if (
      bankNorm === targetNorm ||
      (targetNorm.length >= 3 && (bankNorm.includes(targetNorm) || targetNorm.includes(bankNorm)))
    ) {
      return bank;
    }
  }
  return buildDynamicDomainQuestions(skillName, role);
}
