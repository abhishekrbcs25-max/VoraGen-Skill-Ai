import type { AssessmentQuestion, CareerRole } from '../types';

function mcq(
  id: string,
  skillName: string,
  question: string,
  options: [string, string, string, string],
  correctIndex: 0 | 1 | 2 | 3,
  explanation: string,
): AssessmentQuestion {
  return {
    id,
    skillName,
    kind: 'mcq',
    question,
    options,
    correctIndex,
    explanation,
  };
}

function coding(
  id: string,
  skillName: string,
  question: string,
  starterCode: string,
  testCases: Array<{ args: unknown[]; expected: unknown }>,
  examples: Array<{ input: string; output: string }>,
  explanation: string,
): AssessmentQuestion {
  return {
    id,
    skillName,
    kind: 'coding',
    question,
    options: [],
    correctIndex: 0,
    starterCode,
    testCases,
    examples,
    explanation,
  };
}

